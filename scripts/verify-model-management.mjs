import assert from 'node:assert/strict';
import {saveModel,applyModel,deleteModel,restoreModel} from '../lib/model-data.mjs';
import {emptyWorkspace,writeWorkspace,readWorkspace,validateWorkspace} from '../browser/workspace.mjs';
const memory=new Map(),storage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)};
const source={method:'document',boundary:'processing',products:[{id:'forming',name:'铝型材',production:1000,exportQty:400,fuels:[{quantity:500}],precursors:[]}],report:{installationName:'原企业'},priceOverride:75};
let {workspace,row}=saveModel(emptyWorkspace(),{name:'验证模型',input:source},'model-1');
source.products[0].fuels[0].quantity=999;
assert.equal(row.input.products[0].fuels[0].quantity,500,'Saved snapshots must not change with draft edits');
const applied=applyModel({report:{installationName:'当前企业'},priceOverride:80},row);
assert.equal(applied.report.installationName,'当前企业');assert.equal(applied.priceOverride,80);
applied.products[0].production=2000;applied.boundary='integrated';
assert.equal(row.input.products[0].production,1000,'Applying a model must not mutate its saved data');
({workspace,row}=saveModel(workspace,{id:row.id,name:'修改后的模型',input:applied},'unused'));
assert.equal(workspace.models.length,1);assert.equal(row.id,'model-1');assert.equal(row.input.products[0].production,2000);
assert.equal(row.name,'修改后的模型');assert.equal(row.input.boundary,'integrated');
({workspace}=saveModel(workspace,{name:'副本',input:applied},'model-2'));
workspace=deleteModel(workspace,'model-1');
assert.deepEqual(workspace.models.map(r=>r.id),['model-2']);assert.equal(workspace.modelTrash.length,1);
writeWorkspace(workspace,storage);workspace=readWorkspace(storage);
assert.equal(workspace.modelTrash[0].input.products[0].production,2000,'Deleted model survives reload for recovery');
workspace=restoreModel(workspace,'model-1');
assert.equal(workspace.models.length,2);assert.equal(workspace.modelTrash.length,0);
assert.equal(workspace.models.find(r=>r.id==='model-1').name,'修改后的模型');
assert.throws(()=>saveModel(workspace,{name:'  ',input:applied},'invalid'));
assert.throws(()=>saveModel(workspace,{id:'missing',name:'Invalid',input:applied},'invalid'));
const legacy={schema:1,companies:[],products:[],factors:[],models:[{id:'legacy',name:'旧模型',input:{boundary:'processing',production:113000,fuels:[{quantity:1962}]}}]};
assert.deepEqual(validateWorkspace(legacy).modelTrash,[]);
const oldApplied=applyModel({method:'legacy'},legacy.models[0]);
const oldSaved=saveModel(validateWorkspace(legacy),{id:'legacy',name:'旧模型修改',input:oldApplied},'unused');
assert.equal(oldSaved.row.input.production,113000);assert.equal(oldSaved.row.input.fuels[0].quantity,1962);
writeWorkspace(oldSaved.workspace,storage);assert.equal(readWorkspace(storage).models.length,1);
console.log('Model management passed: edit/update, isolated snapshots, copy, delete/reload/restore, legacy compatibility, validation.');
